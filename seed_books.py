def main():
    os.makedirs(UPLOAD_FOLDER, exist_ok=True)

    try:
        db = mysql.connector.connect(**DB_CONFIG)
    except mysql.connector.Error as e:
        print(f'❌ Ошибка подключения к БД: {e}')
        sys.exit(1)

    cur = db.cursor()
    added = 0

    for (title, description, year, publisher, author, pages,
         color, genre_ids) in BOOKS:

        png_data = make_cover_png(*color)
        md5      = hashlib.md5(png_data).hexdigest()
        mime     = 'image/png'

        try:
            cur.execute(
                'INSERT INTO books (title, description, year, publisher, author, pages) '
                'VALUES (%s, %s, %s, %s, %s, %s)',
                (title, description, year, publisher, author, pages)
            )
            book_id = cur.lastrowid

            for gid in genre_ids:
                cur.execute(
                    'INSERT IGNORE INTO book_genres (book_id, genre_id) VALUES (%s, %s)',
                    (book_id, gid)
                )

            cur.execute(
                'SELECT filename FROM covers WHERE md5_hash = %s LIMIT 1', (md5,)
            )
            existing = cur.fetchone()

            if existing:
                filename = existing[0]
                cur.execute(
                    'INSERT INTO covers (filename, mime_type, md5_hash, book_id) '
                    'VALUES (%s, %s, %s, %s)',
                    (filename, mime, md5, book_id)
                )
            else:

                cur.execute(
                    'INSERT INTO covers (filename, mime_type, md5_hash, book_id) '
                    'VALUES (%s, %s, %s, %s)',
                    ('_tmp_', mime, md5, book_id)
                )
                cover_id = cur.lastrowid
                filename = f'{cover_id}.png'
                cur.execute(
                    'UPDATE covers SET filename = %s WHERE id = %s',
                    (filename, cover_id)
                )

            db.commit()

            filepath = os.path.join(UPLOAD_FOLDER, filename)
            if not os.path.exists(filepath):
                with open(filepath, 'wb') as f:
                    f.write(png_data)

            added += 1
            print(f'[{added:02d}] {title}')

        except Exception as e:
            db.rollback()
            print(f'Ошибка при добавлении «{title}»: {e}')

    cur.close()
    db.close()
    print(f'\nГотово! Добавлено книг: {added} из {len(BOOKS)}')


if __name__ == '__main__':
    print('Добавление тестовых книг...\n')
    main()
